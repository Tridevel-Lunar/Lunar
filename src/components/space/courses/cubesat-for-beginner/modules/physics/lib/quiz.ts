/** Random question order + shuffled choices per question. */
export function buildPhysicsQuizDeck(): PhysicsQuizQuestion[] {
  return shuffleCopy(PHYSICS_QUIZ_QUESTIONS).map((q) => ({
    ...q,
    choices: shuffleCopy(q.choices),
  }));
}
